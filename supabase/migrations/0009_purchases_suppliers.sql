-- Suppliers, purchases (goods received), supplier payments and the Accounts summary.
-- Needs 0007 and 0008. Naming follows the old system: purchase invoice (INV0P/INV1P), supplier payment (CASHP1).

alter table products add column if not exists purchase_price numeric(14,2) not null default 0;   -- last price we paid

alter table stock_movements drop constraint if exists stock_movements_type_check;
alter table stock_movements add constraint stock_movements_type_check
  check (type in ('opening','receive','issue','adjust','sale','sale_cancel','sale_return','market_buy','transfer_in','transfer_out','purchase','purchase_cancel'));

-- ---------- suppliers ----------
create sequence supplier_code_seq;
create table suppliers (
  id uuid primary key default gen_random_uuid(),
  code text not null unique default ('S-' || lpad(nextval('supplier_code_seq')::text, 3, '0')),
  name text not null,
  name_ur text,
  contact text,
  phone text,
  phone2 text,
  address text,
  city text,
  ntn text,
  email text,
  credit_days int not null default 0,
  opening_balance numeric(14,2) not null default 0,      -- what we already owed at the start
  status text not null default 'active' check (status in ('active', 'archived')),
  notes text,
  ora_ccode int unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index suppliers_name_key on suppliers (lower(name));

-- amount > 0: we owe the supplier more (purchase).  amount < 0: we owe less (payment).
create table supplier_ledger (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid not null references suppliers(id) on delete cascade,
  ts timestamptz not null default now(),
  entry_date date not null default ((now() at time zone 'Asia/Karachi')::date),
  type text not null check (type in ('opening','purchase','payment','return','reversal')),
  amount numeric(14,2) not null,
  ref uuid,
  note text
);
create index supplier_ledger_idx on supplier_ledger (supplier_id, ts);
create view supplier_balances with (security_invoker = true) as
  select supplier_id, sum(amount) as balance from supplier_ledger group by supplier_id;
revoke all on supplier_balances from anon, authenticated;

-- ---------- purchases ----------
create sequence purchase_no_seq;
create table purchases (
  id uuid primary key default gen_random_uuid(),
  no text not null unique default ('PUR-' || lpad(nextval('purchase_no_seq')::text, 4, '0')),
  purchase_date date not null default ((now() at time zone 'Asia/Karachi')::date),
  supplier_id uuid not null references suppliers(id),
  supplier_name text not null,
  supplier_inv_no text,
  supplier_inv_date date,
  location_id uuid not null references locations(id),   -- where the goods were received
  discount numeric(14,2) not null default 0,
  line_discount numeric(14,2) not null default 0,
  freight numeric(14,2) not null default 0,              -- transport charged on this purchase (added to what we owe)
  total numeric(14,2) not null default 0,
  paid numeric(14,2) not null default 0,
  remarks text,
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  idem_key text unique,
  created_by uuid references app_users(id) on delete set null,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz
);
create index purchases_supplier_idx on purchases (supplier_id, created_at desc);
create index purchases_date_idx on purchases (purchase_date desc);
create table purchase_items (
  id uuid primary key default gen_random_uuid(),
  purchase_id uuid not null references purchases(id) on delete cascade,
  line_no int not null,
  product_id uuid not null references products(id),
  name text not null,
  qty numeric(14,3) not null check (qty > 0),
  free numeric(14,3) not null default 0,                 -- bonus pieces from the supplier
  cost numeric(14,2) not null,
  disc_pct numeric(5,2) not null default 0,
  line_disc numeric(14,2) not null default 0
);
create index purchase_items_idx on purchase_items (purchase_id);

create table supplier_payments (
  id uuid primary key default gen_random_uuid(),
  no bigint generated by default as identity,
  pay_date date not null default ((now() at time zone 'Asia/Karachi')::date),
  supplier_id uuid not null references suppliers(id),
  amount numeric(14,2) not null check (amount > 0),
  method text not null default 'cash' check (method in ('cash', 'bank', 'cheque')),
  ref_no text,                                           -- cheque number or bank reference
  note text,
  purchase_id uuid references purchases(id),             -- set when paid together with a purchase
  reversed boolean not null default false,
  idem_key text unique,
  created_by uuid references app_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index supplier_payments_idx on supplier_payments (supplier_id, created_at desc);

alter table suppliers         enable row level security;
alter table supplier_ledger   enable row level security;
alter table purchases         enable row level security;
alter table purchase_items    enable row level security;
alter table supplier_payments enable row level security;

-- ---------- record a purchase (goods received) ----------
-- p_lines: [{ "product_id": uuid, "qty": n, "free": n, "cost": n, "disc_pct": n }]
create or replace function create_purchase(
  p_supplier uuid, p_location uuid, p_lines jsonb, p_discount numeric, p_freight numeric, p_paid numeric, p_method text, p_ref text,
  p_supp_no text, p_supp_date date, p_remarks text, p_idem text, p_user uuid
) returns uuid language plpgsql as $$
declare
  sp suppliers%rowtype;
  pr products%rowtype;
  ln jsonb;
  pu_id uuid;
  pu_no text;
  pay_id uuid;
  n int := 0;
  v_q numeric; v_free numeric; v_cost numeric; v_pct numeric; v_ld numeric;
  gross numeric := 0; sum_ld numeric := 0; tot numeric; v_paid numeric;
  v_discount numeric := coalesce(p_discount, 0);
  v_freight numeric := coalesce(p_freight, 0);
  v_method text := coalesce(nullif(p_method, ''), 'cash');
begin
  if p_idem is not null then
    select id into pu_id from purchases where idem_key = p_idem;
    if found then return pu_id; end if;
  end if;
  select * into sp from suppliers where id = p_supplier for update;
  if not found then raise exception 'Choose a supplier.'; end if;
  if sp.status <> 'active' then raise exception 'This supplier is archived. Make them active first.'; end if;
  perform 1 from locations where id = p_location and active;
  if not found then raise exception 'Choose where the goods are received.'; end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then raise exception 'Add at least one item.'; end if;
  if v_discount < 0 or v_freight < 0 then raise exception 'Discount and freight cannot be negative.'; end if;
  if v_method not in ('cash', 'bank', 'cheque') then raise exception 'Choose cash, bank or cheque.'; end if;

  insert into purchases (supplier_id, supplier_name, supplier_inv_no, supplier_inv_date, location_id, discount, freight, remarks, idem_key, created_by)
  values (sp.id, sp.name, nullif(trim(coalesce(p_supp_no, '')), ''), p_supp_date, p_location, v_discount, v_freight,
          nullif(trim(coalesce(p_remarks, '')), ''), p_idem, p_user)
  returning id, no into pu_id, pu_no;

  for ln in select value from jsonb_array_elements(p_lines) loop
    n := n + 1;
    select * into pr from products where id = (ln->>'product_id')::uuid;
    if not found then raise exception 'Part not found (line %).', n; end if;
    v_q := (ln->>'qty')::numeric;
    if v_q is null or v_q <= 0 then raise exception 'Quantity must be above zero for %.', pr.name_en; end if;
    v_free := coalesce((ln->>'free')::numeric, 0);
    if v_free < 0 then raise exception 'Free pieces cannot be negative for %.', pr.name_en; end if;
    v_cost := round((ln->>'cost')::numeric, 2);
    if v_cost is null or v_cost <= 0 then raise exception 'Enter the purchase price for %.', pr.name_en; end if;
    v_pct := coalesce((ln->>'disc_pct')::numeric, 0);
    if v_pct < 0 or v_pct > 100 then raise exception 'Discount percent must be between 0 and 100.'; end if;
    v_ld := round(v_q * v_cost * v_pct / 100);
    insert into purchase_items (purchase_id, line_no, product_id, name, qty, free, cost, disc_pct, line_disc)
    values (pu_id, n, pr.id, pr.name_en, v_q, v_free, v_cost, v_pct, v_ld);
    gross := gross + v_q * v_cost;
    sum_ld := sum_ld + v_ld;
    insert into stock_movements (product_id, location_id, qty, type, note, ref) values (pr.id, p_location, v_q + v_free, 'purchase', pu_no, pu_id);
    update products set purchase_price = v_cost where id = pr.id;
  end loop;

  tot := gross - sum_ld - v_discount + v_freight;
  if tot < 0 then raise exception 'Discount is larger than the total.'; end if;
  v_paid := coalesce(p_paid, 0);
  if v_paid < 0 then raise exception 'Payment cannot be negative.'; end if;
  if v_paid > tot then raise exception 'Payment is larger than the purchase total.'; end if;

  update purchases set total = tot, paid = v_paid, line_discount = sum_ld where id = pu_id;
  insert into supplier_ledger (supplier_id, type, amount, ref) values (sp.id, 'purchase', tot, pu_id);
  if v_paid > 0 then
    insert into supplier_payments (supplier_id, amount, method, ref_no, purchase_id, created_by)
    values (sp.id, v_paid, v_method, nullif(trim(coalesce(p_ref, '')), ''), pu_id, p_user) returning id into pay_id;
    insert into supplier_ledger (supplier_id, type, amount, ref) values (sp.id, 'payment', -v_paid, pay_id);
  end if;
  return pu_id;
end $$;

-- ---------- cancel a purchase (the goods must still be there) ----------
create or replace function cancel_purchase(p_id uuid, p_user uuid) returns void language plpgsql as $$
declare
  pu purchases%rowtype;
  it record;
  pay record;
  have numeric;
  neg boolean;
begin
  select * into pu from purchases where id = p_id for update;
  if not found then raise exception 'Purchase not found.'; end if;
  if pu.status <> 'confirmed' then raise exception 'Only confirmed purchases can be cancelled.'; end if;
  select (value = 'true'::jsonb) into neg from app_settings where key = 'allow_negative_stock';
  neg := coalesce(neg, false);
  for it in select i.product_id, (i.qty + i.free) as q, i.name from purchase_items i where i.purchase_id = pu.id loop
    select coalesce(sum(qty), 0) into have from stock_movements where product_id = it.product_id and location_id = pu.location_id;
    if have < it.q and not neg then
      raise exception 'Cannot cancel: only % of % is left at that location.', have, it.name;
    end if;
    insert into stock_movements (product_id, location_id, qty, type, note, ref) values (it.product_id, pu.location_id, -it.q, 'purchase_cancel', pu.no, pu.id);
  end loop;
  update purchases set status = 'cancelled', cancelled_at = now() where id = pu.id;
  insert into supplier_ledger (supplier_id, type, amount, ref) values (pu.supplier_id, 'reversal', -pu.total, pu.id);
  for pay in select id, amount from supplier_payments where purchase_id = pu.id and not reversed loop
    insert into supplier_ledger (supplier_id, type, amount, ref) values (pu.supplier_id, 'reversal', pay.amount, pay.id);
    update supplier_payments set reversed = true where id = pay.id;
  end loop;
end $$;

-- ---------- pay a supplier ----------
create or replace function pay_supplier(p_supplier uuid, p_amount numeric, p_method text, p_ref text, p_note text, p_idem text, p_user uuid)
returns uuid language plpgsql as $$
declare
  sp suppliers%rowtype;
  pay_id uuid;
  v_method text := coalesce(nullif(p_method, ''), 'cash');
begin
  if p_idem is not null then
    select id into pay_id from supplier_payments where idem_key = p_idem;
    if found then return pay_id; end if;
  end if;
  select * into sp from suppliers where id = p_supplier for update;
  if not found then raise exception 'Choose a supplier.'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter an amount above zero.'; end if;
  if v_method not in ('cash', 'bank', 'cheque') then raise exception 'Choose cash, bank or cheque.'; end if;
  insert into supplier_payments (supplier_id, amount, method, ref_no, note, idem_key, created_by)
  values (sp.id, p_amount, v_method, nullif(trim(coalesce(p_ref, '')), ''), nullif(trim(coalesce(p_note, '')), ''), p_idem, p_user)
  returning id into pay_id;
  insert into supplier_ledger (supplier_id, type, amount, ref) values (sp.id, 'payment', -p_amount, pay_id);
  return pay_id;
end $$;

-- ---------- Accounts ----------
create or replace function account_summary(p_from date, p_to date) returns jsonb language sql stable as $$
  select jsonb_build_object(
    'sales',         coalesce((select sum(total)  from sales where status = 'confirmed' and sale_date between p_from and p_to), 0),
    'returns',       coalesce((select sum(amount) from sale_returns where return_date between p_from and p_to), 0),
    'collected',     coalesce((select sum(amount) from payments where not reversed and pay_date between p_from and p_to), 0),
    'purchases',     coalesce((select sum(total)  from purchases where status = 'confirmed' and purchase_date between p_from and p_to), 0),
    'supplier_paid', coalesce((select sum(amount) from supplier_payments where not reversed and pay_date between p_from and p_to), 0),
    'expenses',      coalesce((select sum(amount) from expenses where not voided and expense_date between p_from and p_to), 0),
    'receivable',    coalesce((select sum(balance) from customer_balances where balance > 0), 0),
    'payable',       coalesce((select sum(balance) from supplier_balances where balance > 0), 0)
  )
$$;

create or replace function cash_book(p_from date, p_to date) returns table (entry_day date, money_in numeric, money_out numeric)
language sql stable as $$
  select x.d, coalesce(sum(x.i), 0), coalesce(sum(x.o), 0) from (
    select pay_date as d, amount as i, 0::numeric as o from payments where not reversed and pay_date between p_from and p_to
    union all select pay_date, 0::numeric, amount from supplier_payments where not reversed and pay_date between p_from and p_to
    union all select expense_date, 0::numeric, amount from expenses where not voided and expense_date between p_from and p_to
  ) x group by x.d order by x.d desc
$$;

revoke all on function create_purchase(uuid, uuid, jsonb, numeric, numeric, numeric, text, text, text, date, text, text, uuid) from public, anon, authenticated;
revoke all on function cancel_purchase(uuid, uuid) from public, anon, authenticated;
revoke all on function pay_supplier(uuid, numeric, text, text, text, text, uuid) from public, anon, authenticated;
revoke all on function account_summary(date, date) from public, anon, authenticated;
revoke all on function cash_book(date, date) from public, anon, authenticated;

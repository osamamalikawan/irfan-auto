-- Returns, expenses, payment vouchers and dispatch printing.
-- Needs 0007_sales.sql.

-- ---------- voucher numbers ----------
-- Received vouchers are customer payments (RV-0001 ...). Existing payments are numbered automatically.
alter table payments add column if not exists no bigint generated by default as identity;

-- ---------- expenses (money paid out; also the "paid" vouchers PV-0001 ...) ----------
create table expenses (
  id uuid primary key default gen_random_uuid(),
  no bigint generated by default as identity,
  expense_date date not null default ((now() at time zone 'Asia/Karachi')::date),
  amount numeric(14,2) not null check (amount > 0),
  category text not null default 'Other',
  note text,
  route_id uuid references routes(id) on delete set null,
  voided boolean not null default false,
  ref_type text,                          -- 'return' for cash refunds made by a return
  ref_id uuid,
  created_by uuid references app_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index expenses_date_idx on expenses (expense_date desc);
alter table expenses enable row level security;

-- ---------- dispatch vouchers ----------
alter table sales add column if not exists dispatch_count int not null default 0;
alter table sales add column if not exists dispatch_last timestamptz;

-- ---------- returns ----------
create sequence return_no_seq;
create table sale_returns (
  id uuid primary key default gen_random_uuid(),
  no text not null unique default ('RET-' || lpad(nextval('return_no_seq')::text, 4, '0')),
  sale_id uuid not null references sales(id),
  return_date date not null default ((now() at time zone 'Asia/Karachi')::date),
  amount numeric(14,2) not null default 0,
  damaged boolean not null default false,       -- damaged goods are not put back into stock
  reason text,
  salesman_id uuid references app_users(id) on delete set null,
  route_id uuid references routes(id) on delete set null,
  area_id uuid references areas(id) on delete set null,
  created_by uuid references app_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index sale_returns_sale_idx on sale_returns (sale_id);
create table sale_return_lines (
  id uuid primary key default gen_random_uuid(),
  return_id uuid not null references sale_returns(id) on delete cascade,
  sale_item_id uuid not null references sale_items(id),
  product_id uuid not null references products(id),
  name text not null,
  qty numeric(14,3) not null check (qty > 0),
  amount numeric(14,2) not null
);
create index sale_return_lines_item_idx on sale_return_lines (sale_item_id);
alter table sale_returns      enable row level security;
alter table sale_return_lines enable row level security;

-- Take goods back from an invoice. p_lines: [{ "item_id": uuid, "qty": number }]
create or replace function create_return(p_sale uuid, p_lines jsonb, p_damaged boolean, p_reason text, p_user uuid)
returns uuid language plpgsql as $$
declare
  s sales%rowtype;
  c customers%rowtype;
  it sale_items%rowtype;
  ln jsonb;
  r_id uuid;
  r_no text;
  q numeric; done numeric; amt numeric; tot numeric := 0;
  loc uuid;
  n int := 0;
  dmg boolean := coalesce(p_damaged, false);
begin
  select * into s from sales where id = p_sale for update;
  if not found or s.status <> 'confirmed' then raise exception 'Invoice not found or cancelled.'; end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then raise exception 'Choose at least one item to return.'; end if;
  select * into c from customers where id = s.customer_id;

  insert into sale_returns (sale_id, damaged, reason, salesman_id, route_id, area_id, created_by)
  values (s.id, dmg, nullif(trim(coalesce(p_reason, '')), ''), s.salesman_id, s.route_id, s.area_id, p_user)
  returning id, no into r_id, r_no;

  for ln in select value from jsonb_array_elements(p_lines) loop
    q := (ln->>'qty')::numeric;
    if q is null or q <= 0 then continue; end if;
    select * into it from sale_items where id = (ln->>'item_id')::uuid and sale_id = s.id;
    if not found then raise exception 'That item is not on this invoice.'; end if;
    select coalesce(sum(l.qty), 0) into done from sale_return_lines l where l.sale_item_id = it.id;
    if q + done > it.qty then raise exception 'Return quantity is larger than what is left to return for %.', it.name; end if;
    amt := round(q * it.price * (1 - it.disc_pct / 100));
    insert into sale_return_lines (return_id, sale_item_id, product_id, name, qty, amount) values (r_id, it.id, it.product_id, it.name, q, amt);
    tot := tot + amt;
    n := n + 1;
    if not dmg then
      -- goods go back to the location most of the item came from
      select location_id into loc from sale_item_allocs where sale_item_id = it.id order by qty desc, id limit 1;
      if loc is not null then
        insert into stock_movements (product_id, location_id, qty, type, note, ref) values (it.product_id, loc, q, 'sale_return', r_no, r_id);
      end if;
    end if;
  end loop;
  if n = 0 then raise exception 'Enter a return quantity above zero.'; end if;

  update sale_returns set amount = tot where id = r_id;
  insert into customer_ledger (customer_id, type, amount, ref) values (s.customer_id, 'return', -tot, r_id);
  if c.is_walk_in then
    -- the cash customer gets the money back at once
    insert into customer_ledger (customer_id, type, amount, ref) values (s.customer_id, 'refund', tot, r_id);
    insert into expenses (amount, category, note, ref_type, ref_id, created_by)
    values (tot, 'Refund', 'Cash refund ' || r_no || ' - Invoice ' || s.no, 'return', r_id, p_user);
  end if;
  return r_id;
end $$;

-- An invoice that has returns can no longer be cancelled (the goods would be put back twice).
create or replace function cancel_sale(p_sale uuid, p_user uuid) returns void language plpgsql as $$
declare
  s sales%rowtype;
  a record;
  pay record;
begin
  select * into s from sales where id = p_sale for update;
  if not found then raise exception 'Invoice not found.'; end if;
  if s.status <> 'confirmed' then raise exception 'Only confirmed invoices can be cancelled.'; end if;
  if exists (select 1 from sale_returns where sale_id = s.id) then raise exception 'This invoice has returns, so it cannot be cancelled.'; end if;
  for a in select i.product_id, al.location_id, al.qty
           from sale_items i join sale_item_allocs al on al.sale_item_id = i.id where i.sale_id = s.id loop
    insert into stock_movements (product_id, location_id, qty, type, note, ref) values (a.product_id, a.location_id, a.qty, 'sale_cancel', s.no, s.id);
  end loop;
  update sales set status = 'cancelled', cancelled_at = now() where id = s.id;
  insert into customer_ledger (customer_id, type, amount, ref) values (s.customer_id, 'reversal', -s.total, s.id);
  for pay in select id, amount from payments where sale_id = s.id and not reversed loop
    insert into customer_ledger (customer_id, type, amount, ref) values (s.customer_id, 'reversal', pay.amount, pay.id);
    update payments set reversed = true where id = pay.id;
  end loop;
end $$;

revoke all on function create_return(uuid, jsonb, boolean, text, uuid) from public, anon, authenticated;
